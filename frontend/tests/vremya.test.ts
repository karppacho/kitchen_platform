import { expect, test } from 'vitest'

import { vremyaDannyh } from '../src/domain/vremya'

test('сегодня по Москве — только часы и минуты', () => {
  expect(vremyaDannyh('2026-09-23T11:35:00Z', new Date('2026-09-23T12:00:00Z'))).toBe('14:35')
})

test('не сегодня — с датой', () => {
  expect(vremyaDannyh('2026-09-22T20:10:00Z', new Date('2026-09-23T09:00:00Z'))).toBe('22.09 23:10')
})

test('граница дня — по Москве, а не по UTC', () => {
  // 22:30 UTC 22.09 — это уже 01:30 23.09 в Москве: тот же день, что и «сейчас».
  expect(vremyaDannyh('2026-09-22T22:30:00Z', new Date('2026-09-23T09:00:00Z'))).toBe('01:30')
})

test('один момент в любом виде ISO 8601 — одно и то же время', () => {
  // Сервер отдаёт время как его отдаёт база: доли секунды бывают не всегда,
  // смещение бывает и «Z», и «+03:00» (docs/FRONTEND.md, GET /api/sync).
  // Живой ответ на бою — последний вид.
  const seychas = new Date('2026-09-23T12:00:00Z')
  for (const iso of [
    '2026-09-23T11:35:02Z',
    '2026-09-23T11:35:02.118883Z',
    '2026-09-23T14:35:02.118883+03:00',
  ]) {
    expect(vremyaDannyh(iso, seychas)).toBe('14:35')
  }
  // И дата: по Москве это уже 23.09, хотя в UTC ещё 22.09.
  const zavtra = new Date('2026-09-24T09:00:00Z')
  for (const iso of [
    '2026-09-22T22:30:00Z',
    '2026-09-22T22:30:00.500001Z',
    '2026-09-23T01:30:00.500001+03:00',
  ]) {
    expect(vremyaDannyh(iso, zavtra)).toBe('23.09 01:30')
  }
})
