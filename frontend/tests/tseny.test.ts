import { expect, test } from 'vitest'

import { dorozhe } from '../src/domain/tseny'

// Деньги приходят строками, и сравнение идёт по строкам как по десятичной
// записи — не через parseFloat (запрещён) и не наивным сравнением строк
// (оно ошибается ровно там, где длины целых частей расходятся).

test('9,50 не дороже 10,00, хотя как строки "9.50" > "10.00"', () => {
  // Наивное сравнение строк здесь дало бы неверный ответ: символ '9'
  // больше символа '1', и "9.50" > "10.00" истинно как строки, хотя
  // 9,50 меньше 10,00 как числа.
  expect(dorozhe('9.50', '10.00')).toBe(false)
})

test('100,00 дороже 99,99, хотя как строки "100.00" < "99.99"', () => {
  // Здесь наивное сравнение строк ошибается в обратную сторону: у целой
  // части разная длина, и "100.00" < "99.99" истинно как строки.
  expect(dorozhe('100.00', '99.99')).toBe(true)
})

test('равные значения — не «дороже»', () => {
  expect(dorozhe('50.00', '50.00')).toBe(false)
})

test('равные значения с разной длиной дробной части — тоже не «дороже»', () => {
  // Дробная часть дополняется нулями до общей длины, а не сравнивается
  // как строки разной длины напрямую.
  expect(dorozhe('50.5', '50.50')).toBe(false)
})

test('цены меню нет — сравнивать не с чем, не «дороже»', () => {
  // price_menu === null — это «маржу посчитать не из чего», а не убыток.
  expect(dorozhe('50.00', null)).toBe(false)
})
