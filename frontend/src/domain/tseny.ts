import { razobratDesyatichnoe, sravnitDesyatichnye } from './sravnenie'

/**
 * Подпись к себестоимости выше цены меню — видимым текстом, а не `title`:
 * всплывающая подсказка на телефоне не показывается вовсе. Направляет к
 * причине: почти всегда это перепутанная единица измерения, а не убыток,
 * и слова «убыток» здесь нет. Одна на оба экрана, чтобы не разошлась.
 */
export const PODPIS_DOROZHE = 'Выше цены меню — проверьте единицы измерения'

/**
 * «Себестоимость выше цены меню?»
 *
 * Деньги приходят с бэкенда строками и строками же остаются, а сравниваются
 * как десятичная запись — тем же `sravnitDesyatichnye`, что сортирует
 * таблицы (почему не float и не строки — см. `sravnenie.ts`).
 *
 * Используется на экране списка блюд и на карточке блюда: обе логики
 * решают одну и ту же задачу, и это самое тонкое место обеих — ошибка в
 * сравнении красит не те строки. Поэтому функция здесь одна, а не
 * продублирована по экранам.
 */
export function dorozhe(uc: string, tsena: string | null): boolean {
  // Цены меню нет вовсе (price_menu === null) — сравнивать не с чем.
  // Это не «убыток», а «маржу посчитать не из чего».
  if (tsena === null) return false
  // Неразбираемое сравнение ставит выше любого числа — это для сортировки.
  // Здесь же «дороже» красит строку тревогой, а по мусору красить нельзя.
  if (razobratDesyatichnoe(uc) === null || razobratDesyatichnoe(tsena) === null) return false
  return sravnitDesyatichnye(uc, tsena) > 0
}
