/**
 * Сравнение денежных строк.
 *
 * Деньги приходят с бэкенда строками и строками же остаются: `parseFloat`
 * над ценой — дефект (теряет копейки на округлении float, см. общие
 * ограничения проекта). Но и наивное сравнение строк (`a > b`) даёт
 * неверный ответ на тех же деньгах: `"9.50" > "10.00"` истинно как
 * сравнение строк (символ `9` больше символа `1`), хотя 9,50 меньше 10,00.
 * `"100.00"` против `"99.99"` ломается по той же причине в обратную
 * сторону — у целой части разная длина. Поэтому сравнение идёт по
 * компонентам десятичной записи (целая часть по длине и значению, дробная
 * часть — дополненная нулями до общей длины), а не как со строками или
 * как с числами.
 *
 * Используется на экране списка блюд и на карточке блюда: обе логики
 * решают одну и ту же задачу («себестоимость выше цены меню?»), и это
 * самое тонкое место обеих — ошибка в сравнении красит не те строки.
 * Поэтому функция здесь одна, а не продублирована по экранам.
 */
export function dorozhe(uc: string, tsena: string | null): boolean {
  // Цены меню нет вовсе (price_menu === null) — сравнивать не с чем.
  // Это не «убыток», а «маржу посчитать не из чего».
  if (tsena === null) return false
  return sravnit(uc, tsena) > 0
}

/** −1, если a < b; 0, если равны; 1, если a > b. Сравнение по разрядам
 *  десятичной записи, без перевода в float. */
function sravnit(a: string, b: string): number {
  const [ac = '0', ad = ''] = a.split('.')
  const [bc = '0', bd = ''] = b.split('.')
  if (ac.length !== bc.length) return ac.length - bc.length
  if (ac !== bc) return ac < bc ? -1 : 1
  const dlina = Math.max(ad.length, bd.length)
  const ap = ad.padEnd(dlina, '0')
  const bp = bd.padEnd(dlina, '0')
  if (ap === bp) return 0
  return ap < bp ? -1 : 1
}
