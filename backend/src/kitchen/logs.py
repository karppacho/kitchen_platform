"""Журнал процессов платформы — один вид у api и у воркера.

Каждая запись — со временем, уровнем и именем журнала: по ним на сервере
видно, когда и насколько серьёзно что-то случилось и в какой части кода.
uvicorn настраивает только свои журналы (``uvicorn.*``), корневой оставляет
пустым — без этой настройки предупреждения ``kitchen.*`` из api шли в
stderr голым текстом.

Секретов в журнал не пишем: ни ключей, ни кук, ни токенов — каждый
``log.*`` в ``kitchen`` пишет только номера, состояния и первую строку
ошибки; причину отказа polza.ai перед журналом маскирует клиент.
"""

from __future__ import annotations

import logging

FORMAT = "%(asctime)s %(levelname)s %(name)s: %(message)s"


def configure_logging() -> None:
    """Записи от INFO — в stderr, со временем, уровнем и именем.

    Корневой журнал уже настроен (второй старт в том же процессе, тесты) —
    ничего не меняет: строки не задваиваются.
    """
    logging.basicConfig(level=logging.INFO, format=FORMAT)
