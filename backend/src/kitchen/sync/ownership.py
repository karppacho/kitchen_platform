"""Кто владеет колонкой — и, следовательно, кто имеет право её писать.

Это не документация, а исполняемое правило. Ошибка здесь не роняет сервис:
она молча стирает работу, существующую в единственном экземпляре — цены,
которые коммерческий отдел вписывал руками, или правки шефа в справочнике.

Приём не выдуман: в `kitchen_bot/src/pricing/exporter.py` функция
``read_existing()`` уже сегодня вычитывает введённые людьми цены перед
перезаписью листа, а ``resolve_price`` задаёт явный приоритет источников.
Здесь это обобщено и перенесено из головы разработчика в тип.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class Owner(StrEnum):
    """Кто источник истины для колонки."""

    HUMAN = "human"
    """Лист главнее всегда. Мы такие колонки читаем и **никогда** не пишем.

    Цена меню в «Блюда», цены коммерсов в расчётке, статусы, комментарии,
    декларация и халяль-сертификат в карточках ингредиентов.
    """

    APP = "app"
    """БД главнее, лист — отрисовка. Перезаписываем свободно.

    UC, маржа, КБЖУ, выход блюда, оба листа конкурентов.
    """

    SHARED = "shared"
    """Владение оспаривается: сюда пишут работающие Telegram-боты.

    Критерий именно такой — «в эту колонку пишет живой бот», а не «это
    справочник». Под него попадают не только ING, Упаковка, Блюда и ТТК, но и
    карточки ингредиентов (их заполняет pizza_bot), листы конкурентов и
    дегустаций. Боты нам не подчиняются, поэтому источник истины — лист.

    Владение переходит к БД после вывода соответствующего бота из
    эксплуатации. См. docs/adr/0001.
    """


class Kind(StrEnum):
    """Как читать содержимое ячейки."""

    TEXT = "text"
    DECIMAL = "decimal"
    PERCENT = "percent"
    """Всегда превращается в долю: «8%» → 0.08."""
    INT = "int"


# ---------------------------------------------------------------------------
# Переключатель этапа
# ---------------------------------------------------------------------------
BOTS_ALIVE = True
"""Работают ли ещё Telegram-боты.

Пока True, платформа не пишет в общий справочник ни при каких условиях:
два писателя без координации дают гонку, в которой проигрывает шеф.

Снимать этот флаг — отдельное осознанное решение фазы 5, а не побочный
эффект чьей-то правки. Смена значения обязана сопровождаться проверкой,
что все три бота действительно остановлены.
"""


class ForbiddenWriteError(RuntimeError):
    """Попытка записать колонку, которой мы не владеем."""


@dataclass(frozen=True, slots=True)
class Column:
    """Колонка листа."""

    letter: str
    """Буква колонки в листе, как её видит человек: «A», «T»."""

    title: str
    """Короткое имя колонки — им подписывают отчёты.

    По умолчанию оно же и сверяется с листом. Если в листе написано что-то
    громоздкое, настоящий текст кладут в :attr:`header`, а здесь остаётся
    читаемое имя.
    """

    field: str
    """Имя поля в нашей модели."""

    kind: Kind
    owner: Owner

    header: str = ""
    """Что реально написано в шапке листа, если это не совпадает с title.

    Шеф формулирует заголовки развёрнуто — «Сроки годности после: - нарезки;
    - фасовки из упаковки производителя; …». Такое не годится в подпись к
    колонке отчёта, но обязано сверяться дословно: расхождение здесь
    означает, что таблица переехала.
    """

    @property
    def expected_header(self) -> str:
        return self.header or self.title

    @property
    def index(self) -> int:
        """Индекс с нуля: «A» → 0, «T» → 19."""
        result = 0
        for char in self.letter.upper():
            result = result * 26 + (ord(char) - ord("A") + 1)
        return result - 1


@dataclass(frozen=True, slots=True)
class SheetSpec:
    """Описание одного листа."""

    spreadsheet: str
    """Ключ настройки с идентификатором таблицы: «kitchen», «tastings»."""

    title: str
    """Имя листа."""

    columns: tuple[Column, ...]

    header_rows: int = 1
    """Сколько строк занимает шапка. Данные начинаются со следующей."""

    key_field: str | None = None
    """Поле-идентификатор строки, если оно есть."""

    fallback_titles: tuple[str, ...] = ()
    """Прежние имена листа.

    «Способы приготовления» когда-то назывался «Впитывание масла», и
    загрузчик обязан пережить переименование, а не упасть.
    """

    @property
    def first_data_row(self) -> int:
        """Номер первой строки с данными, считая с единицы, как в листе."""
        return self.header_rows + 1

    def column(self, field: str) -> Column:
        for column in self.columns:
            if column.field == field:
                return column
        raise KeyError(f"В листе «{self.title}» нет поля «{field}»")

    def writable(self) -> tuple[Column, ...]:
        """Колонки, которые нам разрешено писать прямо сейчас."""
        return tuple(c for c in self.columns if _may_write(c.owner))

    def check_writable(self, *fields: str) -> None:
        """Проверить право записи до того, как что-то уйдёт в лист.

        Вызывается в начале любой операции записи. Дешевле упасть здесь,
        чем обнаружить пропажу чужих данных через несколько дней.
        """
        for field in fields:
            column = self.column(field)
            if _may_write(column.owner):
                continue
            raise ForbiddenWriteError(_explain(self.title, column))


def _may_write(owner: Owner) -> bool:
    if owner is Owner.APP:
        return True
    if owner is Owner.SHARED:
        return not BOTS_ALIVE
    return False


def _explain(sheet: str, column: Column) -> str:
    if column.owner is Owner.HUMAN:
        return (
            f"«{sheet}», колонка {column.letter} ({column.title}) принадлежит людям — "
            f"шеф или коммерческий отдел заполняют её руками. Запись сюда стирает "
            f"работу, которой больше нигде нет."
        )
    return (
        f"«{sheet}», колонка {column.letter} ({column.title}) — общий справочник, "
        f"и в него сейчас пишут Telegram-боты. Пока BOTS_ALIVE=True запись запрещена: "
        f"два писателя без координации дают гонку. См. docs/adr/0001."
    )
